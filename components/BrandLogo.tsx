/** Theme-aware CodeNext IT vector logo derived from public/main-logo.svg. */
export default function BrandLogo({ variant = 'auto', className = 'h-7 w-auto' }: BrandLogoProps) {
  const uid = useId();
  const codeGradId = `${uid}-code`;
  const accentGradId = `${uid}-accent`;

  const colorClass =
    variant === 'dark'
      ? 'text-white'
      : variant === 'light'
        ? 'text-brand-primary'
        : 'text-brand-primary dark:text-white';

  const overrideStyle: CSSProperties | undefined =
    variant === 'dark'
      ? ({
          '--logo-accent-start': '#3B82F6',
          '--logo-accent-end': '#22D3EE',
          '--logo-code-start': '#ffffff',
          '--logo-code-end': '#ffffff',
        } as CSSProperties)
      : variant === 'light'
        ? ({
            '--logo-accent-start': '#0062FF',
            '--logo-accent-end': '#06B6D4',
            '--logo-code-start': '#0062FF',
            '--logo-code-end': '#06B6D4',
          } as CSSProperties)
        : undefined;

  return (
    <svg
      viewBox="0 0 788 98"
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      role="img"
      aria-label="CodeNext IT"
      style={overrideStyle}
      className={`${colorClass} ${className}`.trim()}
    >
      <defs>
        <linearGradient id={codeGradId} x1="0" y1="48" x2="329" y2="48" gradientUnits="userSpaceOnUse">
          <stop offset="0%" style={{ stopColor: 'var(--logo-code-start)' }} />
          <stop offset="100%" style={{ stopColor: 'var(--logo-code-end)' }} />
        </linearGradient>
        <linearGradient id={accentGradId} x1="728" y1="28" x2="783" y2="91" gradientUnits="userSpaceOnUse">
          <stop offset="0%" style={{ stopColor: 'var(--logo-accent-start)' }} />
          <stop offset="100%" style={{ stopColor: 'var(--logo-accent-end)' }} />
        </linearGradient>
      </defs>
      {CODE_PATHS.map((d, idx) => (
        <path key={`c-${idx}`} d={d} fill={`url(#${codeGradId})`} />
      ))}
      {WORDMARK_PATHS.map((d, idx) => (
        <path key={`w-${idx}`} d={d} fill="currentColor" />
      ))}
      {ACCENT_PATHS.map((d, idx) => (
        <path key={`a-${idx}`} d={d} fill={`url(#${accentGradId})`} />
      ))}
    </svg>
  );
}

